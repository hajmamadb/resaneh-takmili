VALID_TYPES = {"SCHOOL","TRADITION","PARADIGM","APPROACH","THEORY","MODEL",
    "FRAMEWORK","HYPOTHESIS","LAW","CONCEPT","METHODOLOGY","METHOD","DESIGN",
    "STRATEGY","TECHNIQUE","INSTRUMENT","SAMPLING","ANALYSIS","QUALITY","ETHICS",
    "SOFTWARE","DISCIPLINE","SUBFIELD"}
VALID_RELS = {"IS_A","PART_OF","BELONGS_TO","INFLUENCED_BY","INFLUENCED",
    "CRITICIZES","EXTENDS","CONTRADICTS","RELATED_TO","APPLIES_TO","USES",
    "MEASURES","ANALYZES","COLLECTS","DEVELOPED_BY","PROPOSED_BY",
    "OPERATIONALIZES","TESTS","DERIVED_FROM","COMPARED_WITH"}

ids = {e["id"] for e in ENTITIES}
errs = []
if len(ids) != len(ENTITIES):
    errs.append("duplicate entity ids")
for e in ENTITIES:
    if e["entity_type"] not in VALID_TYPES:
        errs.append(f"bad type {e['entity_type']}")
    if e["parent_id"] is not None and e["parent_id"] not in ids:
        errs.append(f"bad parent {e['parent_id']}")
seen = set()
for r in RELATIONS:
    k = (r["source_id"], r["target_id"], r["relation_type"])
    if k in seen:
        errs.append(f"dup rel {k}")
    seen.add(k)
    if r["relation_type"] not in VALID_RELS:
        errs.append(f"bad rel type {r['relation_type']}")
    for x in (r["source_id"], r["target_id"]):
        if x not in ids:
            errs.append(f"rel dangling id {x}")
    if not (0 < r["confidence"] <= 1):
        errs.append(f"bad confidence {r['confidence']}")
    if r["verification_status"] != "unverified":
        errs.append(f"bad vstatus {r['verification_status']}")

print(f"entities={len(ENTITIES)} relations={len(RELATIONS)}")
print("ERRORS:" if errs else "OK — all checks passed")
for e in errs: print(" ", e)
