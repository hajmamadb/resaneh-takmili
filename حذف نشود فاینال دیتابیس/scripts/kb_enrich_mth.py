def build_props(old, d, fa):
    p = dict(old)
    p.update({
        "card_type": "روش پژوهش",
        "title_fa": fa,
        "title_en": d["en"],
        "macro_domain": "روش‌شناسی پژوهش",
        "field": {"family": "روش‌شناسی", "parent": "علوم ارتباطات و رسانه", "subfield": fa,
                  "application": "ابزار پژوهش و تولید دانش"},
        "paradigm": None,
        "level": d.get("level", "میانی"),
        "summary": d["summary"],
        "main_problem": d["main_problem"],
        "approach": d["stance"],
        "assumptions": d["stance"],
        "key_concepts": [{"term_fa": t["name"], "definition": t["definition"]} for t in d["techniques"]],
        "techniques": d["techniques"],
        "strengths": d["strengths"],
        "limitations": d["limitations"],
        "applications": d["applications"],
        "example": d["example"],
        "related": d["related"],
        "research_guide": d["research_guide"],
        "sources": d["sources"],
        "recommended_sources": d["sources"][0]["citation"] if d["sources"] else None,
        "tags": d["tags"],
        "detailed_analysis": d["detailed_analysis"],
        "mapping": {"entity_type": "METHOD", "content_type": "روش پژوهش (Method)",
                     "taxonomy_section": "5", "needs_review": False},
        "status": "enriched",
        "quality_score": d["quality_score"],
        "needs_enrichment": False,
        "enriched_at": NOW,
        "enriched_by": STAMP,
    })
    return p

