    cur = conn.cursor()
    codes = list(TEXT.keys())
    cur.execute("SELECT code,id,properties FROM kb_entities WHERE code IN (%s)" %
                ",".join(["%s"] * len(codes)), codes)
    found = {r[0]: (r[1], json.loads(r[2])) for r in cur.fetchall()}
