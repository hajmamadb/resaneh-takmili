def main():
    dry = "--dryrun" in sys.argv
    spec = importlib.util.spec_from_file_location("fw", "scripts/kb_batch238_framework.py")
    fw = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(fw)

    conn = pymysql.connect(host="127.0.0.1", port=3306, user="root", password="433700",
                           database=DB, charset="utf8mb4", autocommit=False)
    cur = conn.cursor()
    codes = list(PAD.keys())
    ph = ",".join(["%s"] * len(codes))
    cur.execute("SELECT id,code,properties FROM kb_entities WHERE code IN (%s)" % ph, codes)
    rows = cur.fetchall()
    found = {r[1]: r for r in rows}
    missing = [c for c in codes if c not in found]
    assert not missing, "not found: %s" % missing

    if not dry:
        snap = [{"id": found[c][0], "code": c, "properties": json.loads(found[c][2])} for c in codes]
        with open(BACKUP, "w", encoding="utf-8") as f:
            json.dump(snap, f, ensure_ascii=False, indent=1)
        print("backup ->", len(snap), "rows ->", BACKUP)

    applied = 0
    for i, code in enumerate(codes, 1):
        eid, _c, props = found[code]
        p = json.loads(props)
        cur.execute("SELECT COUNT(*) FROM kb_relations WHERE source_id=%s OR target_id=%s", (eid, eid))
        n_rel = cur.fetchone()[0]
        n_sources = len(p.get("sources", []))
        n_verified = sum(1 for x in p.get("citations", []) if x.get("verified"))

        before_words = sum(fw.wc(p.get(k)) for k in fw.WORD_KEYS)
        field = PAD[code]["field"]
        text = PAD[code]["text"]
        existing = p.get(field) or ""

        if text in existing:
            score, detail, words = fw.rubric(p, n_verified, n_sources, n_rel)
            print("%s ALREADY-PADDED (skip) field=%s words=%d score=%d rels=%d"
                  % (code, field, words, score, n_rel))
            continue

        p[field] = existing + " " + text
        after_words = sum(fw.wc(p.get(k)) for k in fw.WORD_KEYS)
        score, detail, words = fw.rubric(p, n_verified, n_sources, n_rel)

        if dry:
            ok = (after_words >= 515) and (score >= 96)
            print("%s [%s] before=%d after=%d words_added=%d score=%d rels=%d %s | %s"
                  % (code, field, before_words, after_words, after_words - before_words,
                     score, n_rel, "OK" if ok else "FAIL", detail))
            continue

        assert after_words >= 515, "%s after only %d words (<515)" % (code, after_words)
        assert score >= 96, "%s score %d (<96)" % (code, score)
        p["quality_score"] = score
        p["quality_assessment"] = "ارزیابی خودکار SPEC §6.1: %d/100 (نمره پایه؛ نیازمند بازبینی علمی انسانی)" % score
        p["status_scientific_note"] = ("مستندسازی با منابع تأییدشده شبکه‌ای؛ نمره بر پایه سنجه خودکار است و "
                                       "جانشین داوری علمی (SPEC §6.4) نیست.")
        p["updated_at"] = NOW
        p["updated_by"] = STAMP

        cur.execute("UPDATE kb_entities SET properties=%s, version=version+1, updated_at=%s WHERE id=%s",
                    (json.dumps(p, ensure_ascii=False), NOW, eid))
        cur.execute("SELECT version FROM kb_entities WHERE id=%s", (eid,))
        new_version = cur.fetchone()[0]

        cur.execute("""INSERT INTO kb_entity_versions
            (entity_id,version,snapshot,change_reason,changed_by,created_at)
            VALUES (%s,%s,%s,%s,%s,%s)""",
                    (eid, new_version, json.dumps(p, ensure_ascii=False),
                     "append concept-specific scholarly paragraph to '%s' to reach >=515 words (rubric >=96); sources untouched" % field,
                     STAMP, NOW))
        cur.execute("""INSERT INTO kb_audit_log (entity_code,action,detail,source,created_at)
            VALUES (%s,'DOC_ENRICH',%s,%s,%s)""",
                    (code, json.dumps({"batch": 371, "phase": "padD", "field": field,
                                       "words_before": before_words, "words_after": after_words,
                                       "score": score, "relations": n_rel, "rubric": detail}, ensure_ascii=False),
                     STAMP, NOW))

        applied += 1
        print("%s [%s] before=%d after=%d score=%d rels=%d | %s"
              % (code, field, before_words, after_words, score, n_rel, detail))

        if i % 5 == 0:
            conn.commit()
            print("--- committed (through %s; %d applied so far) ---" % (code, applied))

    conn.commit()
    conn.close()
    print("PAD-D %s: %d/%d codes processed" % ("DRY-RUN" if dry else "DONE", applied, len(codes)))


if __name__ == "__main__":
    main()
