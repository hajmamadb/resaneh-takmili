def build_props(old_props, d):
    p = dict(old_props)
    p.update({
        "card_type": "حوزه مطالعاتی",
        "title_fa": p.get("name_core_fa") or None,  # will set below
        "title_en": d["en"],
        "macro_domain": d["macro_domain"],
        "field": d["field"],
        "paradigm": None,
        "level": d.get("level", "کلان"),
        "summary": d["summary"],
        "main_problem": d["main_problem"],
        "approach": d["approach"],
        "key_concepts": d["key_concepts"],
        "theorists": d["theorists"],
        "theorists_text": d["theorists_text"],
        "history": d["history"],
        "applications": d["applications"],
        "methods": d["methods"],
        "related": d["related"],
        "research_guide": d["research_guide"],
        "sources": d["sources"],
        "recommended_sources": d["sources"][0]["citation"] if d["sources"] else None,
        "tags": d["tags"],
        "detailed_analysis": d["detailed_analysis"],
        "mapping": {"entity_type": "DISCIPLINE", "content_type": "حوزه مطالعاتی (Discipline)",
                     "taxonomy_section": "3", "needs_review": False},
        "status": "enriched",
        "quality_score": d["quality_score"],
        "needs_enrichment": False,
        "enriched_at": NOW,
        "enriched_by": STAMP,
    })
    # clean stray placeholder keys that may have slipped into data
    p["title_fa"] = p["canonical_name_fa"] if "canonical_name_fa" in p else p.get("title_fa")
    return p

