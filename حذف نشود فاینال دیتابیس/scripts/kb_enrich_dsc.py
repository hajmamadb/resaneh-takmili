    missing = [k for k in DATA if k not in codes]
    extra = [k for k in codes if k not in DATA]
    if missing: print("WARN data missing for:", missing)
    if extra: print("WARN db has extra DISCIPLINE:", extra)

    updated = 0
    for code, fa, en, propsraw in rows:
        if code not in DATA:
            continue
        d = DATA[code]
        old = json.loads(propsraw)
        old["canonical_name_fa"] = fa
        props = build_props(old, d)
